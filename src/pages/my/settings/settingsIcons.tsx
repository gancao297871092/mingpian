interface IconPath {
  d: string;
  /** 默认 fill 模式；true 表示描边模式 */
  stroke?: boolean;
  strokeWidth?: number;
}

function renderIcon(paths: IconPath[], size: number, color: string) {
  const s = scaleSizeW(size);
  return (
    <Svg width={s} height={s} viewBox="0 0 20 20" fill="none">
      {paths.map((p, i) =>
        p.stroke ? (
          <Path
            key={i}
            d={p.d}
            stroke={color}
            strokeWidth={p.strokeWidth ?? 1.5}
            strokeLinecap="round"
            strokeLinejoin="round"
          />
        ) : (
          <Path key={i} d={p.d} fill={color} stroke={p.strokeWidth ? color : undefined} strokeWidth={p.strokeWidth} />
        ),
      )}
    </Svg>
  );
}

